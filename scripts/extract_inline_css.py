# -*- coding: utf-8 -*-
"""
Inline CSS extraction for the 29 portals
========================================
Every portal carries ~215 KB of inline <style> that is duplicated verbatim in
all 29 language files and therefore cannot be cached between navigations.
This script moves those blocks, in document order, into one external stylesheet
per portal (`css/inline-core.css` for the Arabic root, `css/inline-<code>.css`
for the others) and links it from the exact place the first block used to be,
so the cascade order is unchanged.

Preconditions verified before writing this script:
  * 0 `url(` and 0 `@import` inside the inline blocks, so no relative asset
    path can break when the CSS moves one directory up.

Usage:  python scripts/extract_inline_css.py [--dry-run]
"""
import io
import os
import re
import sys

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STYLE = re.compile(r'[ \t]*<style[^>]*>(.*?)</style>\r?\n?', re.S)
SKIP_DIRS = {'_site', '.git', 'node_modules', '__pycache__', 'workers', 'dist', 'downloads'}


def portals():
    for name in sorted(os.listdir(ROOT)):
        if name in SKIP_DIRS or name in ('downloads', 'js', 'css', 'assets', 'bg'):
            continue
        path = os.path.join(ROOT, name, 'index.html')
        if os.path.isdir(os.path.join(ROOT, name)) and os.path.isfile(path):
            yield name, path
    root_index = os.path.join(ROOT, 'index.html')
    if os.path.isfile(root_index):
        yield '', root_index


def main():
    dry_run = '--dry-run' in sys.argv
    total_css = 0
    done = 0

    for code, path in portals():
        with io.open(path, encoding='utf-8', newline='') as fh:
            html = fh.read()

        blocks = STYLE.findall(html)
        if not blocks:
            print('  - %s: no inline CSS' % (code or 'root'))
            continue

        css = '\n'.join(b.strip() for b in blocks)
        css_name = 'inline-core.css' if code == '' else 'inline-%s.css' % code
        prefix = './' if code == '' else '../'
        link = '%s<link rel="stylesheet" href="%scss/%s">\n' % ('', prefix, css_name)

        first = True

        def repl(match):
            nonlocal first
            if first:
                first = False
                return link
            return ''

        new_html = STYLE.sub(repl, html)
        css_path = os.path.join(ROOT, 'css', css_name)
        total_css += len(css)
        done += 1

        if not dry_run:
            with io.open(css_path, 'w', encoding='utf-8', newline='\n') as fh:
                fh.write('/* extracted from %s - generated by scripts/extract_inline_css.py */\n'
                         % os.path.basename(os.path.dirname(path) or 'root'))
                fh.write(css)
            with io.open(path, 'w', encoding='utf-8', newline='') as fh:
                fh.write(new_html)

    print('=' * 70)
    print('S&R CoreSync - inline CSS extraction' + (' (DRY RUN)' if dry_run else ''))
    print('=' * 70)
    print('portals processed : %d' % done)
    print('CSS moved         : %.1f KB total (%.1f KB per portal)' % (
        total_css / 1024, total_css / 1024 / max(done, 1)))
    print('=' * 70)
    return 0


if __name__ == '__main__':
    sys.exit(main())
