def apply_translation(html, mapping, lang):
    output = html
    # Sort keys by length descending to replace longest phrases first
    sorted_keys = sorted(mapping.keys(), key=len, reverse=True)
    for k in sorted_keys:
        v = mapping[k]
        output = output.replace(k, v)
    return output

